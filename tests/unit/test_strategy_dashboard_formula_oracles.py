def test_missing_confirmed_daily_boundary_is_unavailable_without_approving_unknown_profiles() -> None:
    """已批准网格的缺点守卫不能误签认未批准的日界线和填补政策。"""
    source = {"series": [
        {"timestamp": "2026-09-01T00:00:00Z", "equity": "100"},
        {"timestamp": "2026-09-03T00:00:00Z", "equity": "121"},
    ]}
    assert evaluate_formula("daily_returns", source) == {
        "status": "blocked_contract", "reason": "BLOCKED_CONTRACT",
    }
    confirmed = {**source, "daily_boundary_profile": {
        "confirmed": True, "timezone": "UTC", "cadence_seconds": 86400,
    }}
    assert evaluate_formula("daily_returns", confirmed) == {
        "status": "unavailable", "daily_returns": None,
    }


def test_confirmed_daily_grid_does_not_approve_cash_flow_adjustment() -> None:
    """确认统计日边界不等于批准入出金调整算法。"""
