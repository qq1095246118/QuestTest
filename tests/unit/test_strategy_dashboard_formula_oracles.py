"""Offline oracle checks against hand-authored goldens, not live product acceptance."""

from __future__ import annotations

import json
from copy import deepcopy
from decimal import Decimal, InvalidOperation, getcontext, localcontext
from pathlib import Path
from typing import Any

import pytest

from service.strategy_dashboard_formula_oracles import evaluate_formula


_DATA_ROOT = Path(__file__).parents[1] / "data" / "strategy_dashboard"
_GOLDENS = [case for name in ("formula_finance.json", "formula_extended.json", "formula_ledger.json", "formula_receipt_registration.json", "formula_deposit_change.json")
            for case in json.loads((_DATA_ROOT / name).read_text(encoding="utf-8"))]


def _equal(actual: Any, expected: Any, tolerance: Decimal) -> None:
    if isinstance(expected, dict):
        assert isinstance(actual, dict)
        assert actual.keys() == expected.keys()
        for key, value in expected.items():
            _equal(actual[key], value, tolerance)
    elif isinstance(expected, list):
        assert isinstance(actual, list)
        assert len(actual) == len(expected)
        for value, reference in zip(actual, expected):
            _equal(value, reference, tolerance)
    elif expected is None or isinstance(expected, bool):
        assert actual is expected
    elif isinstance(expected, int):
        assert type(actual) is int
        assert actual == expected
    elif isinstance(expected, str):
        assert isinstance(actual, str)
        try:
            expected_decimal = Decimal(expected)
        except InvalidOperation:
            assert actual == expected
        else:
            assert Decimal(actual).is_finite()
            assert abs(Decimal(actual) - expected_decimal) <= tolerance
    else:
        raise AssertionError(f"Unexpected golden value type: {type(expected)}")


@pytest.mark.parametrize("case", _GOLDENS, ids=lambda case: case["id"])
def test_formula_matches_independent_fixed_golden(case: dict[str, Any]) -> None:
    """Expected values are stored constants and never generated by the oracle."""
    original = deepcopy(case["inputs"])
    actual = evaluate_formula(case["family"], case["inputs"])
    _equal(actual, case["expected"], Decimal(case.get("tolerance", "1e-35")))
    assert case["inputs"] == original
    assert json.loads(json.dumps(actual, allow_nan=False)) == actual


def test_golden_catalog_ids_are_unique_and_business_titles_are_present() -> None:
    assert len({case["id"] for case in _GOLDENS}) == len(_GOLDENS)
    assert all(case["title"] and case["case_ids"] for case in _GOLDENS)
    assert all(case["expected"] for case in _GOLDENS)


def test_oracle_does_not_change_global_decimal_context() -> None:
    original = getcontext().copy()
    with localcontext() as context:
        context.prec = 9
        evaluate_formula("receivable", {"G": "10.000000025", "Gbase": "10", "share_rate": "0.2"})
        assert getcontext().prec == 9
    assert getcontext().prec == original.prec
    assert getcontext().rounding == original.rounding


@pytest.mark.parametrize("bad", ["NaN", "Infinity", "-Infinity", True, None])
def test_nonfinite_or_boolean_dependency_is_not_a_numeric_result(bad: Any) -> None:
    assert evaluate_formula("wallet", {"E": bad, "U": "0"}) == {
        "status": "unavailable", "wallet": None,
    }


def test_unknown_formula_is_an_error_not_an_empty_success() -> None:
    with pytest.raises(ValueError, match="Unknown formula"):
        evaluate_formula("not_a_formula", {})


def test_event_replay_conflict_requires_revision_contract() -> None:
    result = evaluate_formula("net_deposits", {"events": [
        {"id": "a", "amount": "100", "direction": "in", "qualified": True},
        {"id": "a", "amount": "200", "direction": "in", "qualified": True},
    ]})
    assert result == {"status": "blocked_contract", "reason": "BLOCKED_CONTRACT"}


def test_equal_timestamp_order_conflict_does_not_depend_on_list_order() -> None:
    rows = [
        {"order_id": "o1", "timestamp": "2026-09-01T00:00:00Z", "status": "filled"},
        {"order_id": "o1", "timestamp": "2026-09-01T00:00:00Z", "status": "open"},
    ]
    assert evaluate_formula("order_completion", {"orders": rows}) == {
        "status": "blocked_contract", "reason": "BLOCKED_CONTRACT",
    }
    assert evaluate_formula("order_completion", {"orders": list(reversed(rows))}) == {
        "status": "blocked_contract", "reason": "BLOCKED_CONTRACT",
    }


